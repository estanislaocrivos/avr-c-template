#include "../inc/main.h"

/* ============================================================================================== */

#define ATMEGA2560

/* ============================================================================================== */

int main(void)
{
#ifdef ATMEGA2560
    /* Blinky for ATmega2560 */
    DDRB |= (1 << PB7);
    while (1)
    {
        PORTB ^= (1 << PB7);
        _delay_ms(50);
    }
#else
    /* Loop */
    while (1)
    {
    }
    return 0;
#endif
}

