#include "../inc/main.h"

/* ============================================================================================== */

#define ATMEGA2560

/* ============================================================================================== */

static void atmega2560_blinky(void)
{
    /* Blinky for ATmega2560 MCU */
    DDRB |= (1 << PB7);
    while (1)
    {
        PORTB ^= (1 << PB7);
        _delay_ms(50);
    }
}

/* ============================================================================================== */

int main(void)
{
#ifdef ATMEGA2560
    atmega2560_blinky();
#else
    /* Loop */
    while (1)
    {
    }
#endif
    return 0;
}

