#include "../inc/main.h"

/* ============================================================================================== */

#define ATMEGA2560

/* ============================================================================================== */

static void atmega2560_blinky(void)
{
    /* Blinky for ATmega2560 MCU */
    DDRB |= (1 << PB7);
    while (1)
    {
        PORTB ^= (1 << PB7);
        _delay_ms(100);
    }
}

/* ============================================================================================== */

int main(void)
{
    /* Call C++ code */
    MyClass myObj(42);
    uint8_t v = myObj.getValue();
    v += 1;

    /* Call C code */
    int8_t u = lib_function(0);
    u += 1;

#ifdef ATMEGA2560
    atmega2560_blinky();
#else
    /* Loop */
    while (1)
    {
    }
#endif
    return 0;
}

